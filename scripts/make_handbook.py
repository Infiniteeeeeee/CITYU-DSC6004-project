h("3 研究方法：从原始表到可训练的模型", 1)
h("3.1 第一步：把宽表变成长表（面板）", 2)
p("原始的 volume.csv 是“行=时间、列=站点”的宽表。这种格式适合看，但不适合建模，因为每一列是一个不同的站点，"
  "列与列之间量纲差异巨大。我们把宽表转成“长表”：每一行是一条观测，包含城市、站点、时间、电量，以及我们构造的特征。"
  "这种“同一批对象在多个时间点上被反复观测”的数据，在统计上叫面板数据（panel data）。")
p("转换后的规模：洛杉矶 + 墨尔本合计约 128 万行、286 个站点。长表的好处是：所有站点可以放进同一个模型，"
  "城市和站点属性作为“列”参与预测，而不需要为每个站点单独训练一个模型。")

h("3.2 第二步：特征工程（Feature Engineering）", 2)
p("“特征”就是喂给模型的输入列。原始数据只有“这一刻的电量”，但预测下一小时显然需要“过去发生了什么”。"
  "所以我们构造了三类特征：")
table(["类别", "具体特征", "为什么需要它"],
      [["滞后特征", "前 1 小时、昨日同时刻（24 小时前）、上周同时刻（168 小时前）", "充电行为有很强的惯性和日/周周期"],
       ["滚动统计", "过去 24 小时的均值与标准差、过去 7 天的均值", "刻画“最近的基线水平”和“最近的波动程度”"],
       ["日历特征", "小时（0~23）、星期（0~6）、年内第几天", "区分工作日/周末、白天/夜晚"],
       ["站点静态", "桩数、聚类面积、POI 密度、经纬度", "让模型知道“这个站是大站还是小站、在市中心还是郊区”"]],
      widths=[1.0, 3.3, 2.7],
      caption_text="表 3-1 特征清单。所有滞后与滚动统计都只使用“当前时刻之前”的数据。")
callout("术语小课堂：什么是“滞后”（lag）？",
        "滞后就是把过去某一时刻的值“搬到现在这一行”。例如 lag24 表示“24 小时前的电量”。"
        "预测今天 15 点的需求时，lag24 就是昨天 15 点的值。它是模型能利用的最直接的历史信息。")
callout("术语小课堂：为什么要“shift(1)”？",
        "如果我们用“当前这一小时”的值去算滚动均值，再拿它预测当前这一小时，就等于把答案提前告诉了模型——"
        "这叫数据泄漏（leakage），会让结果虚高。shift(1) 的作用是把窗口整体往前挪一格，确保只用过去的数据。")

p("我们刻意**没有**使用以下信息，原因都是“会造成泄漏或不可用”：")
bullet("sites.csv 里的 total_volume、total_duration、avg_power：它们是对整段时间的汇总，包含了未来的信息。")
bullet("month（月份）作为特征：测试集只有 9 月一个月，用月份等于直接告诉模型答案。")
bullet("电价：零值比例高达 71%~98%，且各城市单位不一致。")
bullet("天气：时区口径不一致（见 3.3）。")

h("3.3 第三步：一个必须做的检查——时区", 2)
p("天气数据是按“当地小时”记录的，但充电数据的时间戳是否也是当地小时，需要验证。方法是比较“充电量的日内峰值时刻”"
  "与“太阳辐射的日内峰值时刻”：太阳辐射一定在当地正午附近达到峰值。")
p("结果：墨尔本两者都出现在 12 点（偏移 0 小时），说明是本地时间；洛杉矶的充电峰值在凌晨 2 点、太阳辐射峰值在 13 点，"
  "相差 13 小时——这不符合任何“本地时间”的常识，说明洛杉矶的时间戳很可能不是本地时间。")
callout("这个检查为什么重要？",
        "如果两边时间不对齐，把天气特征拼进去就会“张冠李戴”：用下午的温度去解释凌晨的充电。"
        "由于无法确认对齐关系，我们选择在两地都不使用天气特征。这是一个保守但正确的决定——"
        "宁可少一个特征，也不要引入错位的变量。")

h("3.4 第四步：时间切分（为什么不能随机切）", 2)
p("机器学习通常把数据随机分成训练集和测试集。但时间序列不能这样做：如果随机打乱，模型在训练时可能已经“见过”"
  "测试时刻附近的数据，评估结果会虚高。正确做法是按时间切：用过去的数据训练，用未来的数据测试。")
p("我们采用“滚动原点验证”（rolling-origin validation）：训练集从 4 月起逐月扩展，分别预测 6、7、8、9 月，"
  "并在训练与测试之间留 1 天间隔。这样每个测试月都对应一个“只使用该月之前数据”的模型，更接近真实使用场景。")
figure(os.path.join(HB, "hb_timeline.png"),
       "图 3-1 滚动原点验证。蓝色是训练区间，红色是测试月，段与段之间留 1 天间隔。")

h("3.5 第五步：评估指标", 2)
p("评估指标回答的是“预测得准不准”。本报告用了四个回归指标和四个分类指标，下面用大白话解释：")
table(["指标", "一句话解释", "取值范围", "怎么读"],
      [["MAE", "平均每个预测错了多少 kWh", "≥0，越小越好", "和数据的量纲一致，直观但不能跨城市比较"],
       ["RMSE", "类似 MAE，但对大误差惩罚更重", "≥0，越小越好", "被极端值主导，需配合 MAE 一起看"],
       ["WAPE", "总误差 ÷ 总真实值", "≥0，越小越好", "**本报告的主指标**，可跨城市比较"],
       ["R²", "模型解释了数据中多少波动", "≤1，越接近 1 越好", "在站点内部计算，避免“猜对大小就得高分”"],
       ["Brier", "预测概率与真实结果的平均平方差", "0~1，越小越好", "概率预测的“准确度+校准度”综合"],
       ["PR-AUC", "在“正例很少”时衡量排序能力", "0~1，越大越好", "基准率越低，越应该看它而不是准确率"],
       ["F1", "精确率与召回率的调和平均", "0~1，越大越好", "需要一个阈值才能算，阈值在验证集上选"]],
      widths=[0.9, 2.6, 1.2, 2.6],
      caption_text="表 3-2 评估指标速查。")
callout("术语小课堂：WAPE 为什么适合这个项目？",
        "不同站点的电量差 400 倍。如果直接算平均误差（MAE），大站会主导结果，小站的错误被淹没。"
        "WAPE 用“总误差 ÷ 总真实值”的方式做归一化，等于给每个站点按电量加权，因此可以跨城市、跨模型比较。"
        "举例：WAPE=0.15 的意思是“总体误差相当于总电量的 15%”。")

# ============================== 4 峰值 ==============================
h("4 峰值事件：一个需要自己定义的概念", 1)
p("数据里并没有“峰值”这一列。它是我们根据业务含义构造出来的标签。定义得好不好，直接决定分类任务有没有意义。")
h("4.1 最直观的定义：超过自己的历史水平", 2)
p("对每个站点、每个小时，我们取它“过去 28 天同一小时”的电量，计算均值与标准差。如果当前小时的电量超过"
  "“均值 + 2 倍标准差”，就记为一次峰值事件。")
figure(os.path.join(HB, "hb_peak_definition.png"),
       "图 4-1 峰值事件的定义。蓝线是实际电量，红色虚线是动态阈值，红点是超过阈值的时刻。")
p("怎么看这张图：阈值不是一条水平线，而是随每天的作息一起起伏——因为它是“同一小时”的历史统计。"
  "只有当某一天的这个时刻明显高于它自己过去四周的水平时，才会被标红。这样定义的好处是："
  "不同规模的站点可以用同一套规则，不会被“大站永远比小站高”干扰。")
callout("为什么不用“容量利用率”来定义峰值？",
        "最自然的想法是“电量 / 装机容量 > 80%”。但这份数据里的 avg_power 是“单次充电的平均功率”，不是装机容量；"
        "我们按 charger_num × avg_power 估算容量后发现，62%~73% 的站点“平均状态”就已经超过估算容量——这在物理上不可能。"
        "所以容量口径不可用，只能改用“相对自身历史”的统计定义。")

h("4.2 峰值率会随月份漂移", 2)
figure(os.path.join(HB, "hb_peak_month.png"),
       "图 4-2 峰值事件占比随月份的变化。")
p("怎么看这张图：同一个定义，在 8 月只标记出 2.1% 的小时，在 9 月却标记出 8.3%（洛杉矶）。"
  "这说明“峰值”本身不是稳定的现象，而是随季节、天气、出行模式变化的。"
  "这也是分类模型在 8 月表现很差、9 月又变好的根本原因——不是模型坏了，而是标签的“基准率”变了。")

