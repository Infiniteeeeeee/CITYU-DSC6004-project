# ============================== 9 结论 ==============================
h("9 结论与研究问题的回答", 1)
p("Q1：历史数据能否预测下一小时需求和峰值事件？", bold=True)
p("能，但要分城市、分条件。在具有真实日内节律的城市（洛杉矶、墨尔本），历史序列足以支撑下一小时预测，"
  "所有模型都稳定优于“昨日同时刻”。峰值侧可以排序，但概率可靠性受标签漂移限制。"
  "阿姆斯特丹这类“小时数据退化”的城市不适合逐小时建模——它的基线误差只有 0.6%，建模没有意义。")
p("Q2：下一小时需求能预测到多准？", bold=True)
p("同一测试集上，洛杉矶 WAPE 0.153（MAE 约 1.10 kWh/站点·小时），墨尔本 0.306（MAE 约 15.5 kWh）；"
  "相对基线分别改善约 46% 与 31%。但误差极不均匀：高需求时段 WAPE 0.11~0.40，接近零需求的小时可达 2.4~354。")
p("Q3：机器学习能否识别潜在峰值时段？", bold=True)
p("能识别，但要区分“排序”与“概率”。排序层面，PR-AUC 是基准率的 3~8 倍，F1 在洛杉矶为 0.42~0.43；"
  "概率层面，由于峰值率在月份间波动 2%~8.5%，跨月校准会失真，8 月甚至接近失效。"
  "此外，结论强烈依赖峰值定义：+2σ 会漂移，P95 最稳，×4 召回最高。")

# ============================== 10 局限 ==============================
h("10 局限性", 1)
bullet("时间跨度只有 6 个月（4—9 月），无法覆盖冬季，也无法外推季节效应。")
bullet("城市间存在半球差异：墨尔本位于南半球，同期是秋冬季，跨城市合并时季节并不对齐。")
bullet("天气特征因时间戳口径不一致而弃用，模型输入不含气象信息。")
bullet("只对洛杉矶与墨尔本建模；阿姆斯特丹因数据退化被排除，其余城市仅用于消融。")
bullet("峰值标签是构造的，不是数据中真实标注的事件；不同定义会给出不同的事件率与结论。")
bullet("LSTM 只跑了单折（9 月）、30 个 epoch 且未早停，也没有做超参数搜索，优势的稳健性有限。")
bullet("墨尔本只有 62 个站点，城市级结论的置信区间较宽。")

